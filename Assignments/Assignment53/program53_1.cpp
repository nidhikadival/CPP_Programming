template <class T>
void CopyArray(T * src, T * dest, int iSize)
{
    int iCnt = 0;

    for(iCnt=0;iCnt<iSize; iCnt++)
    {
        dest[iCnt] = src[iCnt];
    }
    
} // End of CopyArray

