template <class T>
T SecondMax(T * arr, int iSize)
{
    int iCnt = 0;
    T SecondMax = arr[0];
    T Max = arr[0];

    for(int i = 1; i < iSize; i++)
    {
        if(arr[i] > Max)
        {
            SecondMax = Max;
            Max = arr[i];
        }
        else if(arr[i] > SecondMax && arr[i] != Max)
        {
            SecondMax = arr[i];
        }
    }

    return SecondMax;
    
} // End of SecondMax

/////////////////////////////////////////////////////////////////////////////////////////////////
