/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int arr[] = {10,20,30,40,50,60,70,80,90};
    float brr[] = {55.5f,44.2f,22.1f,10.2f};
    int iCnt = 0;

    cout<<"Second maximum number in arr[] is: "<<SecondMax(arr,9)<<"\n";

    cout<<"Second maximum number in brr[] is: "<<SecondMax(brr,4)<<"\n";

    return 0;
}

