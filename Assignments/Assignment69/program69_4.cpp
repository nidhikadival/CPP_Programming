#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Display
//  Description :   Prints the order of characters according to the input using recursion
//  Input :         int
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static char ch = 'A';
    char alpha = 'A' + iNo -1;

    if(ch <= alpha)
    {
        cout<<ch<<" ";
        ch++;
        Display(iNo);
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    
    cout<<"Enter number :\n";
    cin>>iValue;

    Display(iValue);
    cout<<"\n";

    return 0;
}

