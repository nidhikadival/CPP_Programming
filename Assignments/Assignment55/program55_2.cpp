#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Sub
//  Description :   Returns subtarction of two numbers
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          10/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Sub(T no1, T no2)
{
    T sub = 0;

    sub = no1 - no2;

    return sub;
} // End of Sub

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    cout<<"Subtraction of integers is: "<<Sub(50,20)<<"\n";
    cout<<"Subtraction of floats is: "<<Sub(50.22f, 20.11f)<<"\n";
    cout<<"Subtraction of doubles is: "<<Sub(50.43561, 20.34331)<<"\n";

    return 0;
}

