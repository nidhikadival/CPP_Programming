#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Add
//  Description :   Returns addition of two numbers
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          10/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Add(T no1, T no2)
{
    T sum = 0;

    sum = no1 +no2;

    return sum;
} // End of Add

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    cout<<"Addition of integers is: "<<Add(20,50)<<"\n";
    cout<<"Addition of floats is: "<<Add(20.11f,50.22f)<<"\n";
    cout<<"Addition of doubles is: "<<Add(20.34331,50.43561)<<"\n";

    return 0;
}

