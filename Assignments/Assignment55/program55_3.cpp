#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Division
//  Description :   Returns division of two numbers
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          10/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Division(T no1, T no2)
{
    T div = 0;

    if(no2 == 0)
    {
        cout << "Division by zero is not allowed\n";
        return 0;
    }

    div = no1 / no2;

    return div;
}


/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    cout<<"Division of integers is: "<<Division(50,20)<<"\n";
    cout<<"Division of floats is: "<<Division(50.22f, 20.11f)<<"\n";
    cout<<"Division of doubles is: "<<Division(50.43561, 20.34331)<<"\n";

    return 0;
}

