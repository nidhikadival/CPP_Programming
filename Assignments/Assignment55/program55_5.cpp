#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Max
//  Description :   Returns maximum of 4 numbers
//  Input :         T , T , T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          10/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Max(T a, T b, T c, T d)
{
    T max = 0;

    max = a;

    if(b > max)
    {
        max = b;
    }
    if(c > max)
    {
        max = c;
    }
    if(d > max)
    {
        max = d;
    }

    return max;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    cout<<"Maximum number (integer): "<<Max(11,30,4,55)<<"\n";

    cout<<"Maximum number (float): "<<Max(5.2,6.88,6.98,1.7)<<"\n";

    cout<<"Maximum number (double): "<<Max(11.9876, 56.78687, 57.4388, 23.5644)<<"\n";

    return 0;
}

