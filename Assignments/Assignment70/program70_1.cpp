#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Display
//  Description :   Prints a pattern of stars (*) according to the input using recursion
//  Input :         int
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static int i = iNo;

    if(i>=1)
    {
        cout<<i<<" * ";
        i--;
        Display(iNo);
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    
    cout<<"Enter number :\n";
    cin>>iValue;

    Display(iValue);
    cout<<"\n";

    return 0;
}

