#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Fact
//  Description :   Returns the factorial of given number
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Fact(int iNo)
{    
    static int iFact = 1;

    if(iNo >= 1)
    {
        iFact = iFact * iNo;
        iNo--;
        Fact(iNo);
    }

    return iFact;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    int iValue = 0;

    cout<<"Enter number : \n";
    cin>>iValue;

    iRet = Fact(iValue);
    cout<<"Factorial is: "<<iRet<<"\n";

    return 0;
}

