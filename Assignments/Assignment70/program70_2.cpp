#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Sum
//  Description :   Returns the summation of all digits in the given number using recursion
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Sum(int iNo)
{
    int iDigit = 0;
    int iSum = 0;

    if(iNo != 0 )
    {
        iDigit = iNo%10;
        iNo = iNo/10;
        iSum = iDigit + Sum(iNo);
    }
    
    return iSum;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;
    
    cout<<"Enter number :\n";
    cin>>iValue;

    iRet = Sum(iValue);
    cout<<"Summation of all digits : "<<iRet<<"\n";

    return 0;
}

