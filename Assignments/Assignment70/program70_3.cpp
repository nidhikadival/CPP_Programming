/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : strlen
//  Description :   Returns the size of given string recursively
//  Input :         char *
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int strlen(char str[])
{
    if(str[0] == '\0')
    {
        return 0;
    }

    return 1 + strlen(str + 1);
}


/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char string[20];
    int iRet = 0;

    cout<<"Enter the string :\n";
    cin>>string;

    iRet = strlen(string);
    cout<<"Size of the string : "<<iRet<<"\n";

    return 0;
}

