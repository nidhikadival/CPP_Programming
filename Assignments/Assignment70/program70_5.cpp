#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Mult
//  Description :   Returns the product of all digits in the given number using recursion
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Mult(int iNo)
{
    int iDigit = 0;
    int iProduct = 1;

    if(iNo != 0 )
    {
        iDigit = iNo%10;
        iNo = iNo/10;
        iProduct = iDigit * Mult(iNo);
    }
    
    return iProduct;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;
    
    cout<<"Enter number :\n";
    cin>>iValue;

    iRet = Mult(iValue);
    cout<<"Product of all digits : "<<iRet<<"\n";

    return 0;
}

