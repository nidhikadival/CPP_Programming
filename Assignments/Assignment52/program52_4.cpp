#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Max
//  Description :  `Returns the Maximum value element in the given array
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          08/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Max(T * arr, int iSize)
{
    int iCnt = 0;
    T Max = 0;

    for(iCnt=0, Max = arr[0]; iCnt<iSize; iCnt++)
    {
        if(arr[iCnt] > Max)
        {
            Max = arr[iCnt];
        }
    }

    return Max;
} // End of Max

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int arr[] = {10,20,30,40,50};
    float brr[] = {10.10f,50.50f,30.30f,40.40f,20.20f};

    int iRet = 0;
    float fRet = 0.0f;

    iRet = Max(arr,5);
    cout<<"Maximum of all integers is: "<<iRet<<"\n";

    fRet = Max(brr,5);
    cout<<"Maximum of all float values is: "<<fRet<<"\n";

    return 0;
}

