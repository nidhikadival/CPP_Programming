#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Multiply
//  Description :   Multiplies two given numbers
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          08/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T Multiply(T No1, T No2)
{
    T Ans = 0;
    
    Ans = No1 * No2;

    return Ans;

} // End of Multiply

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    float fRet = 0.0f;
    double dRet = 0.0;

    iRet = Multiply(12,2);
    cout<<"Multiplication of Integers is: "<<iRet<<"\n";

    fRet = Multiply(10.20f,20.10f);
    cout<<"Multiplication of Floats is: "<<fRet<<"\n";

    dRet = Multiply(10.555,4.111);
    cout<<"Multiplication of Doubles is: "<<dRet<<"\n";

    return 0;
}

