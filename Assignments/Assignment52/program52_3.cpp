#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : AddN
//  Description :  `Adds all the numbers in a given array
//  Input :         T , T
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          08/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T AddN(T * arr, int iSize)
{
    int iCnt = 0;
    T Sum = 0;

    for(iCnt=0; iCnt<iSize; iCnt++)
    {
        Sum = Sum + arr[iCnt];
    }

    return Sum;
} // End of AddN

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int arr[] = {10,20,30,40,50};
    float brr[] = {10.10f,20.20f,30.30f,40.40f,50.50f};

    int iRet = 0;
    float fRet = 0.0f;

    iRet = AddN(arr,5);
    cout<<"Sum of all integers is: "<<iRet<<"\n";

    fRet = AddN(brr,5);
    cout<<"Sum of all float values is: "<<fRet<<"\n";

    return 0;
}

