#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : SumOdd
//  Description :   Prints addition of all odd numbers
//  Input :         T * , int
//  Output :        T
//  Author :        Nidhi Girish Kadival
//  Date :          09/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
T SumOdd(T * arr, int iSize)
{
    int iCnt = 0;
    T sum = 0;

    for(iCnt=0;iCnt<iSize; iCnt++)
    {
        if( (arr[iCnt]%2) != 0)
        {
            sum = sum + arr[iCnt];
        }
    }
    
    return sum;
} // End of SumOdd

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int arr[] = {1,2,3,4,5,6,7,8,9};
    
    int iRet = 0;
   
    iRet = SumOdd(arr,9);
    cout<<"Summation of all odd integers is: "<<iRet<<"\n";

    return 0;
}

