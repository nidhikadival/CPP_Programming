#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Display
//  Description :   Prints the order of characters a to f using recursion
//  Input :         -
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    static char ch = 'a';

    if(ch <= 'f')
    {
        cout<<ch<<" ";
        ch++;
        Display();
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    cout<<"\n";

    return 0;
}

