#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Display
//  Description :   Prints a pattern of stars (*) using recursion
//  Input :         -
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          09/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 1;

    if(i<=5)
    {
        cout<<"* ";
        i++;
        Display();
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    cout<<"\n";

    return 0;
}

