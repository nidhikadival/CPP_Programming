#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Display
//  Description :   Displays the given symbol the no of times given by user
//  Input :         T , int 
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          07/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
void Display(T value, int iSize)
{
    int iCnt = 0;

    for(iCnt=1;iCnt<=iSize; iCnt++)
    {
        cout<<value<<"\t";
    }
    cout<<"\n";
} // End of Display

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display("M",7);
    Display(11,3);
    Display(3.7,6);

    return 0;
}

