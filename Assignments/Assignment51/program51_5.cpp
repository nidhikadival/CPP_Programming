#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Reverse
//  Description :   Reverses the array
//  Input :         T * , int
//  Output :        void
//  Author :        Nidhi Girish Kadival
//  Date :          08/01/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

template <class T>
void Reverse(T * arr, int iSize)
{
    int iStart = 0;
    int iEnd = iSize -1;
    T temp = 0;

    while(iEnd>iStart)
    {
        temp = arr[iStart];
        arr[iStart] = arr[iEnd];
        arr[iEnd] = temp;

        iEnd--;
        iStart++;
    }

} // End of Reverse

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int arr[] = {10,20,30,10,30,40,10,40,10};
    int iCnt = 0;
    
    Reverse(arr,9);

    for(iCnt=0;iCnt<9;iCnt++)
    {
        cout<<arr[iCnt]<<" ";
    }
    cout<<"\n";

    char brr[] = {'a','b','b','a','o','b'};

    Reverse(brr,6);

    for(iCnt=0;iCnt<6;iCnt++)
    {
        cout<<brr[iCnt]<<" ";
    }
    cout<<"\n";

    return 0;
}

