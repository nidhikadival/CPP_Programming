#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Max
//  Description :   Returns the maximum digit in the given number 
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          10/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Max(int iNo)
{
    int iDigit = 0;
    int iMax = 0;

    if(iNo == 0)
    {
        return 0;
    }

    iDigit = iNo % 10;
    iMax = Max(iNo / 10);

    if(iDigit > iMax)
    {
        return iDigit;
    }
    else
    {
        return iMax;
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    int iValue = 0;

    cout<<"Enter number :\n";
    cin>>iValue;

    iRet = Max(iValue);
    cout<<"Maximum digit is : "<<iRet<<"\n";
    return 0;
}

