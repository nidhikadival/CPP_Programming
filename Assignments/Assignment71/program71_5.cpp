#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Reverse
//  Description :   Returns number in reverse acc to the given number
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          10/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Reverse(int iNo)
{
    static int iRev = 0;

    if(iNo == 0)
    {
        return iRev;
    }

    iRev = (iRev * 10) + (iNo % 10);

    Reverse(iNo / 10);

    return iRev;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    int iValue = 0;

    cout<<"Enter number :\n";
    cin>>iValue;

    iRet = Reverse(iValue);
    cout<<"Number in reverse : "<<iRet<<"\n";
    return 0;
}

