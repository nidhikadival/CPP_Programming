#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : WhiteSpaces
//  Description :   Returns the no of white spaces int given string recursively
//  Input :         char *
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          10/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int WhiteSpaces(char * str)
{
    int iCount = 0;

    if(*str == '\0')        
    {
        return 0;
    }

    if(*str == ' ')
    {
        iCount = 1;
    }

    return iCount + WhiteSpaces(str + 1);
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char string[20];
    int iRet = 0;

    cout<<"Enter string: \n";
    cin.getline(string,20);

    iRet = WhiteSpaces(string);
    cout<<"No of white spaces : "<<iRet<<"\n";

    return 0;
}

