/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Min
//  Description :   Returns the minimum digit in the given number 
//  Input :         int
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          10/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Min(int iNo)
{
    int iDigit = 0;
    int iMin = iNo % 10;  

    iNo = iNo / 10;

    if(iNo == 0)
    {
        return iMin;
    }

    iDigit = Min(iNo);

    if(iDigit < iMin)
    {
        iMin = iDigit;
    }

    return iMin;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iRet = 0;
    int iValue = 0;

    cout<<"Enter number :\n";
    cin>>iValue;

    iRet = Min(iValue);
    cout<<"Minimum digit is : "<<iRet<<"\n";
    return 0;
}

