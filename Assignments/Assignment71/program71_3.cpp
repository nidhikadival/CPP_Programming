#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Function Name : Small
//  Description :   Returns the no of lower case alphabet in given string recursively
//  Input :         char *
//  Output :        int
//  Author :        Nidhi Girish Kadival
//  Date :          10/02/2026
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int Small(char * str)
{
    int iCount = 0;

    if(*str == '\0')        
    {
        return 0;
    }

    if((*str >= 'a') && (*str<='z'))
    {
        iCount = 1;
    }

    return iCount + Small(str + 1);
}

/////////////////////////////////////////////////////////////////////////////////////////////////
// 
//  Entry point function for the application
// 
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    char string[20];
    int iRet = 0;

    cout<<"Enter string: \n";
    cin.getline(string,20);

    iRet = Small(string);
    cout<<"No of lower case alphabets : "<<iRet<<"\n";

    return 0;
}

